// BoardSvg.cpp — serialises the board display list (BoardRender.h) to a standalone
// SVG file. The same display list is painted by the Qt board view, so the file and
// the GUI always show the same picture.
#include <cmath>
#include <iomanip>
#include <sstream>
#include <string>

#include "BoardRender.h"
#include "Export.h"

namespace pcbv {
namespace {

constexpr double kMilToMm = 0.0254;

std::string f(double value) {
    std::ostringstream ss;
    ss << std::fixed << std::setprecision(3) << value;
    return ss.str();
}

std::string hex(std::uint32_t rgb) {
    static const char* digits = "0123456789abcdef";
    std::string out = "#";
    for (int shift = 20; shift >= 0; shift -= 4) out += digits[(rgb >>shift) & 0xF];
    return out;
}

std::string pointsAttr(const std::vector<Point>& points) {
    std::string out;
    for (const auto& point : points) {
        out += f(point.x);
        out += ",";
        out += f(point.y);
        out += " ";
    }
    return out;
}

std::string escapeXml(const std::string& value) {
    std::string out;
    out.reserve(value.size());
    for (char c : value) {
        switch (c) {
            case '&': out += "&amp;"; break;
            case '<': out += "&lt;"; break;
            case '>': out += "&gt;"; break;
            case '"': out += "&quot;"; break;
            default: out += c;
        }
    }
    return out;
}

} // namespace

std::string toSvg(const Document& doc, const BoardRenderOptions& options) {
    const BoardRenderList list = buildBoardRender(doc, options);
    if (list.empty()) return std::string();

    // The display list works in abstract units; for the file we also want a real
    // physical size, which comes back from `unitsPerMil`.
    const double widthMm = list.width / list.unitsPerMil * kMilToMm;
    const double heightMm = list.height / list.unitsPerMil * kMilToMm;

    std::ostringstream svg;
    svg << "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
        << "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"" << f(widthMm)
        << "mm\" height=\"" << f(heightMm) << "mm\" viewBox=\"0 0 " << f(list.width) << " "
        << f(list.height) << "\">\n";
    svg << "  <title>" << escapeXml(doc.fileName) << " — PCB View</title>\n";
    svg << "  <desc>Generated by pcbv from " << escapeXml(doc.fileName) << ". Board "
        << f(list.boardWidthMil * kMilToMm) << " x " << f(list.boardHeightMil * kMilToMm)
        << " mm; " << doc.geometry.tracks.size() << " tracks, " << doc.geometry.pads.size()
        << " pads, " << doc.geometry.vias.size() << " vias.</desc>\n";

    for (const auto& primitive : list.primitives) {
        const std::string color = hex(primitive.color);
        switch (primitive.kind) {
            case RenderPrimitive::Kind::Line:
                if (primitive.points.size() < 2) break;
                svg << "  <line x1=\"" << f(primitive.points[0].x) << "\" y1=\""
                    << f(primitive.points[0].y) << "\" x2=\"" << f(primitive.points[1].x)
                    << "\" y2=\"" << f(primitive.points[1].y) << "\" stroke=\"" << color
                    << "\" stroke-width=\"" << f(primitive.strokeWidth)
                    << "\" stroke-linecap=\"round\"/>\n";
                break;
            case RenderPrimitive::Kind::Polygon: {
                if (primitive.points.size() < 3) break;
                const bool open = !primitive.closed;
                svg << "  <" << (open ? "polyline" : "polygon") << " points=\""
                    << pointsAttr(primitive.points) << "\" fill=\""
                    << (primitive.filled ? color : "none") << "\"";
                if (primitive.filled) svg << " fill-opacity=\"" << f(primitive.opacity) << "\"";
                if (primitive.strokeWidth >0.0) {
                    svg << " stroke=\"" << color << "\" stroke-width=\""
                        << f(primitive.strokeWidth) << "\"";
                    if (primitive.dashed) svg << " stroke-dasharray=\"6 4\"";
                }
                svg << "/>\n";
                break;
            }
            case RenderPrimitive::Kind::Circle:
                svg << "  <circle cx=\"" << f(primitive.center.x) << "\" cy=\""
                    << f(primitive.center.y) << "\" r=\"" << f(primitive.radius) << "\" fill=\""
                    << (primitive.filled ? color : "none") << "\"";
                if (primitive.filled) svg << " fill-opacity=\"" << f(primitive.opacity) << "\"";
                if (primitive.strokeWidth >0.0) {
                    svg << " stroke=\"" << color << "\" stroke-width=\""
                        << f(primitive.strokeWidth) << "\"";
                }
                svg << "/>\n";
                break;
            case RenderPrimitive::Kind::Text:
                svg << "  <text x=\"" << f(primitive.x) << "\" y=\"" << f(primitive.y)
                    << "\" font-family=\"Arial, Helvetica, sans-serif\" font-size=\""
                    << f(primitive.fontSize) << "\" fill=\"" << color
                    << "\" text-anchor=\""
                    << (primitive.textAnchor == 1 ? "start"
                                                  : primitive.textAnchor == 2 ? "end" : "middle")
                    << "\"";
                if (primitive.rotation != 0.0) {
                    svg << " transform=\"rotate(" << f(primitive.rotation) << " "
                        << f(primitive.x) << " " << f(primitive.y) << ")\"";
                }
                if (primitive.strokeWidth >0.0) {
                    svg << " paint-order=\"stroke\" stroke=\"#10141a\" stroke-width=\""
                        << f(primitive.strokeWidth) << "\"";
                }
                svg << ">" << escapeXml(primitive.text) << "</text>\n";
                break;
        }
    }

    svg << "</svg>\n";
    return svg.str();
}

} // namespace pcbv
